// Offline generation: consumes the checked-in schema, never imports the backend.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const source = readFileSync(new URL('../../docs/openapi.json', import.meta.url), 'utf8');
const document = JSON.parse(source);
const schemas = document.components.schemas;
const reference = (ref) => `Components[${JSON.stringify(ref.split('/').at(-1))}]`;

function typeOf(schema) {
  if (schema.$ref) return reference(schema.$ref);
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((x) => JSON.stringify(x)).join(' | ');
  if (schema.anyOf || schema.oneOf) return (schema.anyOf ?? schema.oneOf).map(typeOf).join(' | ');
  if (schema.type === 'null') return 'null';
  if (schema.type === 'string') return 'string';
  if (schema.type === 'number' || schema.type === 'integer') return 'number';
  if (schema.type === 'boolean') return 'boolean';
  if (schema.type === 'array') {
    if (schema.prefixItems) return `readonly [${schema.prefixItems.map(typeOf).join(', ')}]`;
    return `ReadonlyArray<${typeOf(schema.items ?? {})}>`;
  }
  if (schema.type === 'object' || schema.properties) {
    const required = new Set(schema.required ?? []);
    // Discriminated action payloads always send their type explicitly on the wire.
    if (schema.properties?.type?.const) required.add('type');
    return `{ ${Object.entries(schema.properties ?? {}).map(([key, value]) =>
      `readonly ${JSON.stringify(key)}${required.has(key) ? '' : '?'}: ${typeOf(value)};`).join(' ')} }`;
  }
  return 'unknown';
}

const names = Object.keys(schemas);
const generated = '// Generated by scripts/generate-contracts.mjs; do not edit.\n'
  + `// docs/openapi.json SHA-256: ${createHash('sha256').update(source).digest('hex')}\n`
  + 'export interface Components {\n'
  + names.map((name) => `  ${name}: ${typeOf(schemas[name])};`).join('\n')
  + '\n}\n'
  + names.map((name) => `export type ${name} = Components[${JSON.stringify(name)}];`).join('\n')
  + '\nexport const schemas = ' + JSON.stringify(schemas, null, 2) + ' as const;\n';
const target = new URL('../src/api/generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) throw new Error('Generated API contracts are stale');
} else {
  writeFileSync(target, generated);
}
console.log(`${names.length} OpenAPI components ${process.argv.includes('--check') ? 'verified' : 'generated'} offline`);
